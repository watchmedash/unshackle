// ─── i18n Engine ──────────────────────────────────────────────────────────────
const LANG_KEY = 'art_lang';

function getLang() {
  return localStorage.getItem(LANG_KEY) || 'en';
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  applyLang(lang);
}

function applyLang(lang) {
  const isAr = lang === 'ar';
  const t = translations.ar;

  // Direction + font
  document.documentElement.lang = lang;
  document.documentElement.dir  = isAr ? 'rtl' : 'ltr';
  document.body.classList.toggle('lang-ar', isAr);
  document.body.classList.toggle('lang-en', !isAr);

  // Toggle button label
  const btn = document.getElementById('langToggle');
  if (btn) btn.classList.toggle('is-ar', isAr);

  if (!isAr) {
    // Restore all original English text from data-i18n-en attributes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const orig = el.getAttribute('data-i18n-en');
      if (orig !== null) el.textContent = orig;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const orig = el.getAttribute('data-i18n-placeholder-en');
      if (orig !== null) el.placeholder = orig;
    });
    return;
  }

  // Apply Arabic translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!t[key]) return;
    // Save original English text on first run
    if (el.getAttribute('data-i18n-en') === null) {
      el.setAttribute('data-i18n-en', el.textContent);
    }
    el.textContent = t[key];
  });

  // Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (!t[key]) return;
    if (el.getAttribute('data-i18n-placeholder-en') === null) {
      el.setAttribute('data-i18n-placeholder-en', el.placeholder);
    }
    el.placeholder = t[key];
  });
}

// Toggle on button click
document.addEventListener('DOMContentLoaded', () => {
  function syncToggleBtns(isAr) {
    ['langToggle', 'langToggleMobile'].forEach(id => {
      const btn = document.getElementById(id);
      if (btn) btn.classList.toggle('is-ar', isAr);
    });
  }

  ['langToggle', 'langToggleMobile'].forEach(id => {
    const btn = document.getElementById(id);
    if (btn) {
      btn.addEventListener('click', () => {
        const next = getLang() === 'ar' ? 'en' : 'ar';
        setLang(next);
        syncToggleBtns(next === 'ar');
        // Close mobile menu after toggling
        const navLinks = document.getElementById('navLinks');
        const burger = document.getElementById('burger');
        if (navLinks) navLinks.classList.remove('open');
        if (burger) burger.classList.remove('open');
        document.body.style.overflow = '';
      });
    }
  });

  // Apply saved preference on load
  const lang = getLang();
  applyLang(lang);
  syncToggleBtns(lang === 'ar');
});
